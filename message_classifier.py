_SPACE_RE = re.compile(r"\s+")


def classify_message(text: str) -> MessageClassification:
    normalized = _SPACE_RE.sub(" ", text).strip()
    matched_terms: list[str] = []
    for term in _MAINTENANCE_TERMS:
        if term in normalized and not any(term in matched for matched in matched_terms):
            matched_terms.append(term)
    matched = tuple(matched_terms)
    if matched:
        return MessageClassification("maintenance_request", matched)
    return MessageClassification("general_message")
